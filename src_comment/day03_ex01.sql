-- Давай разберем его работу по шагам, так как тут используется очень популярный прием поиска «дыр» в данных с помощью `RIGHT JOIN` и `IS NULL` (так называемый *Anti-Join*).

-- ### Как это работает:

-- 1. **`generate_series('2022-01-01','2022-01-10', interval '1 day') as g`**
-- Здесь создается «эталонный» календарь — непрерывный список всех дат с 1 по 10 января 2022 года с шагом в 1 день. Это правая таблица в нашем объединении.
-- 2. **`(select * from person_visits po where person_id in (1,2)) as po`**
-- Это подзапрос (левая таблица), который берет из таблицы визитов `person_visits` только те записи, которые относятся к людям с ID 1 или 2.
-- 3. **`RIGHT JOIN ... ON po.visit_date = g`**
-- База данных берет наш эталонный календарь (правую часть) и пытается приклеить к нему реальные визиты (левую часть) по совпадению дат.
-- * Поскольку используется `RIGHT JOIN`, в результате **гарантированно останутся все 10 дней** из сгенерированного календаря.
-- * Если в какой-то из дней визит был, данные из таблицы `po` заполнятся.
-- * Если в какой-то день визитов не было, база данных вместо значений из таблицы `po` (включая `po.id`) подставит пустоту — `NULL`.


-- 4. **`where po.id is null`**
-- Это фильтр, который делает всю магию. Он отбрасывает все дни, к которым успешно приклеился реальный визит, и оставляет **только те дни, где вместо id стоит `NULL**`. То есть те самые даты, в которые визитов не было.
-- 5. **`select g::date as missing_date` и `order by 1**`
-- В конце запрос берет сгенерированную дату, приводит ее к типу `date` (отбрасывая время, если оно было), называет колонку `missing_date` и сортирует итоговый список по возрастанию.

