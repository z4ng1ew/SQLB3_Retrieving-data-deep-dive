-- **1. Создаем Календарь**

-- > `generate_series('2022-01-01','2022-01-10', interval '1 day') as g`

-- Система рисует на стене ровно 10 квадратиков: 1 января, 2 января... и так до 10-го. Это наш идеальный, непрерывный список дат. В коде он называется буквой `g`.

-- **2. Собираем стикеры**

-- > `(select * from person_visits po where person_id in (1,2)) as po`

-- Мы роемся в архиве и достаем только те стикеры (записи о визитах), где расписался либо сотрудник 1, либо сотрудник 2. Остальные нас не волнуют. Эту стопку стикеров мы называем `po`.

-- **3. Клеим стикеры на календарь (Ключевой момент!)**

-- > `RIGHT JOIN ... ON po.visit_date = g`

-- Слово **RIGHT** говорит базе данных: *"Календарь (он написан справа) — это святое! Оставь на стене все 10 дней, ни один не выкидывай"*.
-- Мы начинаем клеить стикеры на дни:

-- * На 1 января стикер есть? Наклеили.
-- * На 2 января никто не пришел? Квадратик в календаре остается **пустым**. В SQL эта пустота называется **`NULL`**.

-- **4. Выкидываем лишнее**

-- > `where po.id is null`

-- Мы смотрим на наш календарь со стикерами. Нас просили найти дни прогулов. Поэтому мы срываем со стены и выбрасываем все дни, где наклеен хоть один стикер.
-- Мы оставляем только те даты, которые остались **пустыми** (`is null`).

-- **5. Отдаем результат**

-- > `select g::date as missing_date ... order by 1`

-- Мы просто переписываем оставшиеся пустые даты на чистый лист (`select`), называем этот лист «пропущенные_дни» (`missing_date`) и сортируем их по порядку (`order by 1`), чтобы боссу было удобно читать.

-- ---

-- **Краткая суть:** Создали идеальный календарь $\rightarrow$ попытались наложить на него реальные визиты $\rightarrow$ оставили только те дни, куда визиты не "прилипли".

