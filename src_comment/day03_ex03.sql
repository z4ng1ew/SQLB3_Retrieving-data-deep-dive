## ❓ Возможные вопросы на защите

### **Q1: Что такое CTE?**

**A:** "CTE — это Common Table Expression, временная именованная таблица, которая существует только в рамках одного запроса. Создаётся с помощью `WITH ... AS (...)`. После создания её можно использовать как обычную таблицу в основном запросе."

---

### **Q2: Зачем нужен CTE, если можно использовать подзапрос?**

**A:** "CTE делает код более **читаемым** и **структурированным**. В задании 01 `generate_series` был прямо в JOIN, что сложнее понять. В задании 03 я сначала создаю таблицу дат, потом её использую — логика понятнее."

---

### **Q3: Можно ли использовать CTE несколько раз?**

**A:** "Да! Это одно из главных преимуществ. Если мне нужно использовать таблицу `g` в нескольких местах запроса, я создаю её один раз в CTE, а потом многократно использую."

**Пример:**

```sql
WITH g AS (...)
SELECT * FROM table1 JOIN g ...
UNION
SELECT * FROM table2 JOIN g ...;
```

---

### **Q4: В чём разница между CTE и временной таблицей (CREATE TEMP TABLE)?**

**A:**

| CTE | Временная таблица |
|-----|-------------------|
| Существует только в одном запросе | Существует до конца сессии |
| Не создаётся физически | Создаётся на диске |
| Быстрее для разовых операций | Лучше для многократного использования |
| `WITH ... AS` | `CREATE TEMP TABLE` |

---

### **Q5: Можно ли в CTE делать INSERT/UPDATE?**

**A:** "Да, PostgreSQL поддерживает модифицирующие CTE (data-modifying CTE), но в моём запросе я использую CTE только для SELECT — для создания набора дат."

