## 💡 Когда использовать CTE?

### **✅ Используй CTE когда:**

1. **Сложные подзапросы** — нужно сделать код читаемым
2. **Переиспользование** — одна и та же выборка нужна несколько раз
3. **Рекурсия** — для рекурсивных запросов (WITH RECURSIVE)

**Пример переиспользования:**

```sql
WITH dates AS (
    SELECT generate_series(...) AS date
)
SELECT * FROM table1 JOIN dates ON ...
UNION
SELECT * FROM table2 JOIN dates ON ...;
--                         ^^^^^
--                         используем CTE дважды!
```

---

### **❌ НЕ используй CTE когда:**

1. **Простой запрос** — CTE добавит лишний код
2. **Разовая выборка** — проще написать подзапрос

