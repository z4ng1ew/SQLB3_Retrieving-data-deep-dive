## 📋 Структура CTE запроса

```sql
WITH имя_CTE AS (
    -- Любой SELECT запрос
    SELECT ...
)
-- После WITH блока - основной запрос
SELECT ...
FROM таблица
JOIN имя_CTE ON ...;
```

**Можно создать несколько CTE:**

```sql
WITH 
    cte1 AS (SELECT ...),
    cte2 AS (SELECT ...),
    cte3 AS (SELECT ...)
SELECT ... FROM cte1 JOIN cte2 JOIN cte3;
```

