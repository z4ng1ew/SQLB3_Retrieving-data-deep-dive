## ❓ Возможные вопросы на защите

### **Q1: Что такое Self-JOIN?**

**A:** "Self-Join — это самосоединение, когда таблица соединяется сама с собой. Используются два псевдонима (`p1` и `p2`), чтобы различать 'две копии' одной таблицы. Это позволяет сравнивать строки внутри одной таблицы друг с другом."

---

### **Q2: Зачем условие `p1.id > p2.id`?**

**A:** "Это условие решает две проблемы:
1. **Предотвращает самосоединение** — человек не соединяется сам с собой
2. **Убирает дубликаты** — пара показывается только один раз (Anna-Andrey, но не Andrey-Anna)

Без него получили бы самосоединения (Anna+Anna) и дубликаты (Anna+Andrey И Andrey+Anna)."

---

### **Q3: Можно ли без Self-JOIN решить эту задачу?**

**A:** "Теоретически можно через подзапросы, но это будет сложнее и менее читаемо. Self-JOIN — это стандартный и самый понятный способ для таких задач."

**Альтернатива (хуже):**

```sql
SELECT p1.name, p2.name, p1.address
FROM person p1, person p2
WHERE p1.id > p2.id AND p1.address = p2.address;
--    ^^^^^^^^^^^^^^
--    старый синтаксис (неявный JOIN)
```

**Self-JOIN с ON читаемее!**

---

### **Q4: Почему `p1.address = p2.address`, а не другое условие?**

**A:** "Потому что адрес — это то, что нас интересует! Задача — найти людей с **общим адресом**. Если бы искали людей одного возраста, было бы `p1.age = p2.age`."

---

### **Q5: Что если в городе живёт только один человек?**

**A:** "Он **не попадёт** в результат, потому что INNER JOIN требует совпадения. Если в Novosibirsk живёт только Nataly, для неё нет пары, и она не появится в результате."

**Пример:**

```
Nataly (id=8, Novosibirsk) — единственная в городе
↓
Нет других людей с address = 'Novosibirsk'
↓
Нет пары → не в результате
```

---

### **Q6: Сколько строк будет, если в городе 3 человека?**

**A:** "Для 3 человек будет **3 пары** (комбинации по 2 из 3):"

**Формула:** C(n, 2) = n × (n-1) / 2

**Пример:** Kate, Denis, Elvira (3 человека в Kazan)

```
Пары:
1. Denis + Kate    (id 4 > 3)
2. Elvira + Kate   (id 5 > 3)
3. Elvira + Denis  (id 5 > 4)

Итого: 3 строки
```

**Для 4 человек:** 4 × 3 / 2 = 6 пар  
**Для 5 человек:** 5 × 4 / 2 = 10 пар

