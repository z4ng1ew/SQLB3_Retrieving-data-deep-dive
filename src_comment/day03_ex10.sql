    --                                     без этого: Anna+Andrey И Andrey+Anna
    --                                     с этим: только Andrey+Anna (2 > 1)
    
    AND p1.address = p2.address         -- основное условие: одинаковый адрес

ORDER BY 1, 2, 3;                       -- упорядоченный вывод

-- ============================================================================
-- SELF-JOIN = таблица соединяется САМА С СОБОЙ
-- Используем два псевдонима (p1, p2) для одной таблицы
--
-- КРИТИЧЕСКОЕ УСЛОВИЕ: p1.id > p2.id
-- - Убирает самосоединение (Anna с Anna)
-- - Убирает дубликаты (только Andrey+Anna, БЕЗ Anna+Andrey)
-- - Каждая пара показывается ОДИН раз
--
-- РЕЗУЛЬТАТ:
-- Andrey  | Anna   | Moscow
-- Denis   | Kate   | Kazan
-- Elvira  | Denis  | Kazan
-- Elvira  | Kate   | Kazan
-- Peter   | Irina  | Saint-Petersburg
-- ============================================================================
