```

**Говоришь:**
"Это **критически важное** условие! Оно решает две проблемы:

**Проблема 1: Самосоединение**
Без этого условия Anna соединилась бы сама с собой:
- Anna (id=1) + Anna (id=1) ❌

**Проблема 2: Дубликаты**
