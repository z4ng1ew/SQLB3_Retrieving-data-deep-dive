## 🔍 Операторы сравнения

### **`age > 25` означает "строго больше":**

```
age > 25

25 → ❌ НЕ подходит (равно, не больше)
26 → ✅ Подходит
27 → ✅ Подходит
...
```

### **Другие операторы:**

| Оператор | Значение | Пример |
|----------|----------|--------|
| `>` | Больше | `age > 25` (26, 27, 28...) |
| `>=` | Больше или равно | `age >= 25` (25, 26, 27...) |
| `<` | Меньше | `age < 25` (24, 23, 22...) |
| `<=` | Меньше или равно | `age <= 25` (25, 24, 23...) |
| `=` | Равно | `age = 25` (только 25) |
| `!=` или `<>` | Не равно | `age != 25` (всё кроме 25) |

