## 💡 Особенности WHERE с AND

### **Что такое AND:**

```sql
WHERE условие1 AND условие2
```

**Означает:** "Должны выполняться **ОБА** условия **ОДНОВРЕМЕННО**"

**Таблица истинности:**

| условие1 | условие2 | Результат |
|----------|----------|-----------|
| ✅ true | ✅ true | ✅ **Подходит** |
| ✅ true | ❌ false | ❌ Не подходит |
| ❌ false | ✅ true | ❌ Не подходит |
| ❌ false | ❌ false | ❌ Не подходит |

---

### **Примеры:**

```
Anna: gender = 'female' (✅) AND age > 25 (❌ 16 < 25)
      → ✅ AND ❌ = ❌ НЕ ПОДХОДИТ

Kate: gender = 'female' (✅) AND age > 25 (✅ 33 > 25)
      → ✅ AND ✅ = ✅ ПОДХОДИТ

Peter: gender = 'female' (❌ male) AND age > 25 (❌ 24 < 25)
       → ❌ AND ❌ = ❌ НЕ ПОДХОДИТ

Nataly: gender = 'female' (✅) AND age > 25 (✅ 30 > 25)
        → ✅ AND ✅ = ✅ ПОДХОДИТ
```

