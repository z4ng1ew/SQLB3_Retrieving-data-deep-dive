## 📋 Альтернативные способы написания

### **Вариант 1: Явное название колонки в ORDER BY**

```sql
SELECT name
FROM person
WHERE gender = 'female' AND age > 25
ORDER BY name;        -- вместо ORDER BY 1
```

---

### **Вариант 2: С явным ASC (ascending = по возрастанию)**

```sql
SELECT name
FROM person
WHERE gender = 'female' AND age > 25
ORDER BY name ASC;    -- явно указываем "по возрастанию"
```

**Примечание:** `ASC` — это **по умолчанию**, поэтому обычно не пишут.

---

### **Вариант 3: Если бы нужна сортировка наоборот**

```sql
SELECT name
FROM person
WHERE gender = 'female' AND age > 25
ORDER BY name DESC;   -- DESC = descending (по убыванию, Z→A)

-- Результат: Nataly, Kate, Elvira
```

