## ❓ Возможные вопросы на защите

### **Q1: Почему `age > 25`, а не `age >= 25`?**

**A:** "Задание требует **строго больше** 25 лет. Это означает 26, 27, 28... но не 25. Если бы использовал `>=`, то человек ровно 25 лет тоже попал бы в результат."

**Разница:**

```sql
age > 25   → 26, 27, 28... (25 НЕ включается)
age >= 25  → 25, 26, 27... (25 включается)
```

---

### **Q2: Что если поменять порядок условий в WHERE?**

**A:** "Порядок не важен для результата! `AND` коммутативен."

**Эквивалентные запросы:**

```sql
-- Вариант 1:
WHERE gender = 'female' AND age > 25

-- Вариант 2:
WHERE age > 25 AND gender = 'female'
```

**Результат одинаковый!** Но первый вариант чуть логичнее: сначала отсеиваем по полу, потом по возрасту.

---

### **Q3: Зачем ORDER BY, если и так можно прочитать?**

**A:** "Без `ORDER BY` порядок строк **не гарантирован** и может быть случайным. База данных может выдать результат в любом порядке. `ORDER BY` гарантирует упорядоченный вывод."

**Без ORDER BY (случайный порядок):**

```
Kate
Nataly
Elvira
```

**С ORDER BY (алфавит):**

```
Elvira
Kate
Nataly
```

---

### **Q4: Можно ли без WHERE вообще?**

**A:** "Да, можно. Но тогда получим **всех** людей из таблицы, а не только женщин старше 25."

```sql
-- Без WHERE:
SELECT name FROM person ORDER BY 1;

-- Результат: Anna, Andrey, Denis, Dmitriy, Elvira, Irina, Kate, Nataly, Peter
-- (все 9 человек)
```

---

### **Q5: Что означает `ORDER BY 1`?**

**A:** "`ORDER BY 1` означает сортировку по **первой колонке** в SELECT. В моём случае это `name`."

**Эквивалентные записи:**

```sql
ORDER BY 1          -- по номеру колонки
ORDER BY name       -- по названию колонки
```

**Оба работают одинаково!**

