-- # 🤯 Порядок написания VS порядок выполнения SQL

-- ## 🎭 ГЛАВНАЯ ИДЕЯ

-- **SQL — это странный язык!**

-- - **Порядок НАПИСАНИЯ:** SELECT → FROM → WHERE
-- - **Порядок ВЫПОЛНЕНИЯ:** FROM → WHERE → SELECT

-- Это как **рецепт**, который читается не по порядку! 🍕

-- ---

-- ## 📖 Аналогия: Рецепт пиццы

-- ### **Как НАПИСАН рецепт:**

-- ```
-- 1. ПОДАЙ пиццу на стол
-- 2. ВОЗЬМИ тесто из холодильника  
-- 3. ДОБАВЬ только помидоры (не грибы)
-- ```

-- ### **Как ГОТОВИШЬ на самом деле:**

-- ```
-- Шаг 1: ВОЗЬМИ тесто (сначала нужно тесто!)
-- Шаг 2: ДОБАВЬ помидоры (потом ингредиенты)
-- Шаг 3: ПОДАЙ на стол (в конце подача)
-- ```

-- **Точно так же работает SQL!**

-- ---

-- ## 🔍 SQL: порядок написания

-- ```sql
-- SELECT name          -- Строка 1: что показать
-- FROM pizzeria        -- Строка 2: откуда взять
-- WHERE rating > 4     -- Строка 3: какие отфильтровать
-- ```

-- **Ты пишешь сверху вниз:** SELECT → FROM → WHERE

-- ---

-- ## ⚡ SQL: порядок выполнения

-- **База данных выполняет НАОБОРОТ:**

-- ```
-- Шаг 1: FROM pizzeria         ← Сначала! (Иду в таблицу)
--        ↓
-- Шаг 2: WHERE rating > 4      ← Потом! (Фильтрую строки)
--        ↓
-- Шаг 3: SELECT name           ← В конце! (Выбираю колонки)
-- ```

-- ---

-- ## 🧠 ПОЧЕМУ так?

-- ### **Логика базы данных:**

-- ```
-- Чтобы ВЫБРАТЬ колонку (SELECT),
-- сначала нужно ЗНАТЬ, из какой таблицы брать (FROM)!
-- ```

-- **Пример проблемы:**

-- ```sql
-- SELECT name
-- FROM ???
-- ```

-- **База думает:** 😵 "Какой `name`? Из какой таблицы? Я не знаю!"

-- **Поэтому база СНАЧАЛА читает FROM, потом SELECT!**

-- ---

-- ## 📊 Визуализация выполнения

-- ### **Что ты пишешь:**

-- ```sql
-- 1  SELECT name, rating     ← Пишешь ПЕРВЫМ
-- 2  FROM pizzeria           ← Пишешь ВТОРЫМ
-- 3  WHERE rating > 4        ← Пишешь ТРЕТЬИМ
-- ```

-- ### **Что делает база:**

-- ```
-- Шаг 1 (читает строку 2):
-- FROM pizzeria
-- ↓
-- ┌─────────────────┐
-- │ id | name       │ rating |
-- │ 1  | Pizza Hut  | 4.6    |
-- │ 2  | Dominos    | 4.3    |
-- │ 3  | Best Pizza | 2.3    |
-- └─────────────────┘
-- "Ага! Работаю с таблицей pizzeria"

-- Шаг 2 (читает строку 3):
-- WHERE rating > 4
-- ↓
-- ┌─────────────────┐
-- │ id | name       | rating |
-- │ 1  | Pizza Hut  | 4.6    | ✓ оставляю
-- │ 2  | Dominos    | 4.3    | ✗ убираю
-- │ 3  | Best Pizza | 2.3    | ✗ убираю
-- └─────────────────┘

-- Шаг 3 (читает строку 1):
-- SELECT name, rating
-- ↓
-- ┌────────────┬────────┐
-- │ name       | rating |
-- │ Pizza Hut  | 4.6    |
-- └────────────┴────────┘
-- "Беру только эти колонки"
-- ```

-- ---

-- ## 🎯 Почему нельзя писать FROM первым?

-- ### **Попытка написать "логично":**

-- ```sql
-- FROM pizzeria
-- SELECT name
-- WHERE rating > 4
-- ```

-- ❌ **ОШИБКА СИНТАКСИСА!**

-- **Почему?**

-- **SQL имеет СТРОГИЙ СИНТАКСИС (правила грамматики):**
-- - Запрос ДОЛЖЕН начинаться со слова `SELECT`
-- - Это правило языка SQL (как в русском предложение начинается с большой буквы)

-- **Это как в русском языке:**

-- ❌ Неправильно: "магазин В пошёл Я"  
-- ✅ Правильно: "Я пошёл в магазин"

-- Хотя мозг и так поймёт, но **правила языка** требуют определённый порядок!

-- ---

-- ## 🔬 Полный порядок выполнения SQL

-- ```sql
-- SELECT name, COUNT(*) as cnt    -- 5. Выбираем колонки
-- FROM pizzeria                   -- 1. Берём таблицу
-- WHERE rating > 4                -- 2. Фильтруем строки
-- GROUP BY name                   -- 3. Группируем
-- HAVING COUNT(*) > 1             -- 4. Фильтруем группы
-- ORDER BY cnt DESC               -- 6. Сортируем
-- LIMIT 10                        -- 7. Ограничиваем количество
-- ```

-- **Порядок выполнения:**

-- ```
-- 1. FROM       ← Какая таблица?
-- 2. WHERE      ← Какие строки?
-- 3. GROUP BY   ← Как группировать?
-- 4. HAVING     ← Какие группы оставить?
-- 5. SELECT     ← Какие колонки показать?
-- 6. ORDER BY   ← Как отсортировать?
-- 7. LIMIT      ← Сколько строк вывести?
-- ```

-- ---

-- ## 🎨 Почему псевдоним работает в SELECT?

-- ### **Твой исходный вопрос:**

-- ```sql
-- SELECT p.name           -- Как база знает, что такое "p"?
-- FROM pizzeria p         -- Потому что ТУТ объявлен псевдоним!
-- ```

-- ### **Ответ:**

-- **Хотя SELECT пишется ПЕРВЫМ, выполняется он ПОСЛЕДНИМ!**

-- ```
-- Ты пишешь:
-- 1. SELECT p.name    ← пишешь первым, но "p" пока неизвестен
-- 2. FROM pizzeria p  ← пишешь вторым

-- База выполняет:
-- 1. FROM pizzeria p  ← выполняет первым → запоминает: p = pizzeria
-- 2. SELECT p.name    ← выполняет вторым → уже знает что такое "p"!
-- ```

-- ---

