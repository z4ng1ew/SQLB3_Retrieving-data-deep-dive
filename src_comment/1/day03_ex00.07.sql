-- ## 💡 Почему SQL так устроен?

-- ### **Исторические причины:**

-- SQL создавался в 1970-х как **декларативный язык**

-- **Декларативный = говоришь ЧТО хочешь, а не КАК это сделать**

-- ```sql
-- SELECT name          -- ЧТО хочу: имена
-- FROM pizzeria        -- ОТКУДА: из пиццерий  
-- WHERE rating > 4     -- КАКИЕ: с рейтингом > 4
-- ```

-- Ты описываешь **результат**, а не **шаги** его получения.

-- ---

-- ## 🎯 Аналогия: заказ в ресторане

-- ### **Неправильно (как процесс):**

-- ```
-- 1. Пойди на кухню
-- 2. Возьми сковородку
-- 3. Поджарь яйца
-- 4. Подай мне
-- ```

-- ### **Правильно (что хочешь):**

-- ```
-- "Хочу яичницу с беконом"
-- ```

-- **SQL работает так же:**

-- ```sql
-- SELECT name           -- "Хочу имена"
-- FROM pizzeria         -- "из пиццерий"
-- WHERE rating > 4      -- "с хорошим рейтингом"
-- ```

-- База сама решает, КАК это сделать быстрее!

-- ---

-- ## 📝 Шпаргалка

-- | Порядок | Что пишешь | Что выполняется |
-- |---------|------------|-----------------|
-- | 1 | `SELECT` | 5. Выбор колонок |
-- | 2 | `FROM` | 1. Выбор таблицы |
-- | 3 | `WHERE` | 2. Фильтр строк |
-- | 4 | `GROUP BY` | 3. Группировка |
-- | 5 | `HAVING` | 4. Фильтр групп |
-- | 6 | `ORDER BY` | 6. Сортировка |
-- | 7 | `LIMIT` | 7. Ограничение |

