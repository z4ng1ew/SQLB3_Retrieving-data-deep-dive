-- ## ✅ Финальный ответ на твой вопрос

-- **Вопрос:** Почему SQL читает сначала SELECT, а потом FROM?

-- **Ответ:** 

-- **НЕ читает!** SQL читает в **ДВА ЭТАПА:**

-- 1. **Синтаксический разбор** (проверка грамматики):
--    - Читает сверху вниз: SELECT → FROM → WHERE
--    - Проверяет: "Запрос начинается с SELECT? ✓ Хорошо"

-- 2. **Выполнение** (получение результата):
--    - Выполняет в логическом порядке: FROM → WHERE → SELECT
--    - Сначала берёт таблицу, потом фильтрует, потом выбирает колонки

-- **Псевдоним `p` работает потому что:**
-- - Хотя `SELECT p.name` пишется ПЕРВЫМ
-- - Выполняется он ПОСЛЕДНИМ (когда `p` уже известен из `FROM pizzeria p`)

