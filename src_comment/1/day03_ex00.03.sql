🧠 КАК база понимает связь?
Объявление псевдонима происходит в строке FROM


FROM <имя_таблицы> <псевдоним>
     ^^^^^^^^^^^^^ ^^^^^^^^^^^
     реальное      короткое




Примеры:

FROM pizzeria p
--   ^^^^^^^^ ^
--   |        └─ с этого момента "p" = "pizzeria"
--   └─ это реальное имя таблицы в базе данных



FROM person_visits pv
--   ^^^^^^^^^^^^^ ^^
--   |             └─ с этого момента "pv" = "person_visits"
--   └─ реальное имя таблицы




📝 Шаг 3: Используем псевдоним

SELECT p.name
--     ^
--     └─ "p" уже известен! (объявили в FROM)
FROM pizzeria p
```

**Пошаговое чтение базой данных:**
```
Шаг 1: Читаю FROM pizzeria p
       ↓
       Запоминаю: p = pizzeria

Шаг 2: Читаю SELECT p.name
       ↓
       "p" — это что? Смотрю в память: p = pizzeria
       ↓
       p.name = pizzeria.name
       ↓
       Беру колонку name из таблицы pizzeria