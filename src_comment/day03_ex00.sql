-- # 🎭 Псевдонимы в SQL — полный разбор

-- ## 1️⃣ Что такое `p.name`?

-- ### **`p` — это псевдоним для таблицы `pizzeria`**

-- ```sql
-- FROM pizzeria p
-- --   ^^^^^^^^ ^
-- --   таблица  псевдоним (короткое имя)
-- ```

-- **`p.name` расшифровывается как:** "поле `name` из таблицы `pizzeria`"

-- ---

-- ## 📊 Реальный пример из ТВОЕЙ базы

-- ### Таблица `pizzeria`:
-- ```
-- | id | name       | rating |
-- |----|------------|--------|
-- | 1  | Pizza Hut  | 4.6    |
-- | 2  | Dominos    | 4.3    |
-- | 3  | DoDo Pizza | 3.2    |
-- ```

-- ### Обращение к колонке `name`:

-- ```sql
-- -- БЕЗ псевдонима:
-- SELECT pizzeria.name FROM pizzeria

-- -- С псевдонимом:
-- SELECT p.name FROM pizzeria p
-- --     ^^^^^                ^
-- --     p = pizzeria         объявили псевдоним
-- ```

-- **Оба запроса ИДЕНТИЧНЫ!** `p` = короткая запись вместо `pizzeria`

-- ---

-- ## 🎯 Зачем нужны псевдонимы?

-- ### **Причина 1: JOIN — несколько таблиц**

-- **БЕЗ псевдонимов (НЕ РАБОТАЕТ!):**

-- ```sql
-- SELECT name, rating
-- FROM pizzeria 
-- LEFT JOIN person_visits ON id = pizzeria_id
-- WHERE id IS NULL
-- --    ^^
-- -- ОШИБКА! Какой id? Из какой таблицы?
-- -- В pizzeria есть id, в person_visits тоже есть id!
-- ```

-- **С псевдонимами (РАБОТАЕТ!):**

-- ```sql
-- SELECT p.name, p.rating
-- FROM pizzeria p 
-- LEFT JOIN person_visits pv ON p.id = pv.pizzeria_id
-- WHERE pv.id IS NULL
-- --    ^^^^^^
-- -- ясно: проверяем id из person_visits!
-- ```

-- ---

-- ### **Причина 2: Читаемость**

-- **Длинно:**
-- ```sql
-- SELECT pizzeria.name, pizzeria.rating
-- FROM pizzeria 
-- LEFT JOIN person_visits ON pizzeria.id = person_visits.pizzeria_id
-- WHERE person_visits.id IS NULL
-- ```

-- **Коротко:**
-- ```sql
-- SELECT p.name, p.rating
-- FROM pizzeria p 
-- LEFT JOIN person_visits pv ON p.id = pv.pizzeria_id
-- WHERE pv.id IS NULL
-- ```

-- **Экономия:** вместо `pizzeria` пишем `p`, вместо `person_visits` — `pv`

-- ---

-- ### **Причина 3: Self-JOIN (таблица сама с собой)**

-- **Задание 10 из твоих документов:**
-- ```sql
-- SELECT p1.name, p2.name, p1.address
-- FROM person p1 
-- INNER JOIN person p2 ON p1.address = p2.address
-- --         ^^^^^^ ^^
-- -- ДВЕ копии таблицы person!
-- ```

-- **БЕЗ псевдонимов это НЕВОЗМОЖНО написать!**

-- ```sql
-- -- ЭТО НЕ РАБОТАЕТ:
-- FROM person INNER JOIN person -- какая person где???
-- ```

