# 🌳 Разбор дерева реляционной алгебры

## Читаем дерево **СНИЗУ ВВЕРХ** (как растет дерево! 🌱→🌳)

```
         π*        ← Шаг 3: SELECT * (выбрать все колонки)
         ↑
         σ         ← Шаг 2: WHERE clause (отфильтровать строки)
         ↑
         ×         ← Шаг 1: CROSS JOIN (соединить таблицы)
        ↗ ↖
       R   S      ← Исходные таблицы
```

---

## 📖 Пошаговое объяснение

### **Шаг 1: R × S (крестик) = CROSS JOIN**

**Что происходит:** Берем **каждую** строку из таблицы R и соединяем с **каждой** строкой из таблицы S.

**Пример:**

```
Таблица R (люди):        Таблица S (города):
| name  |                | city   |
|-------|                |--------|
| Anna  |                | Moscow |
| Peter |                | Kazan  |

CROSS JOIN (R × S):
| name  | city   |
|-------|--------|
| Anna  | Moscow |  ← Anna со всеми городами
| Anna  | Kazan  |
| Peter | Moscow |  ← Peter со всеми городами
| Peter | Kazan  |
```

**В SQL:** `FROM R CROSS JOIN S`

---

### **Шаг 2: σ (сигма) = WHERE**

**Что происходит:** Из всех комбинаций **отфильтровываем** нужные строки.

**Символ σ** = **селекция** (от слова "select" = выбрать)

**Пример:**

```
После CROSS JOIN у нас:
| name  | city   |
|-------|--------|
| Anna  | Moscow |
| Anna  | Kazan  |
| Peter | Moscow |
| Peter | Kazan  |

WHERE name = 'Anna' (фильтр σ):
| name  | city   |
|-------|--------|
| Anna  | Moscow |  ← только Anna осталась
| Anna  | Kazan  |
```

**В SQL:** `WHERE clause` (где clause = какое-то условие)

---

### **Шаг 3: π* (пи) = SELECT***

**Что происходит:** Выбираем, **какие колонки** показать в результате.

**Символ π** = **проекция** (какие столбцы взять)

**π*** означает **все колонки** (звездочка = все)

**Пример:**

```
Если бы было π(name):     Но у нас π*:
| name  |                 | name  | city   |
|-------|                 |-------|--------|
| Anna  |                 | Anna  | Moscow |
| Anna  |                 | Anna  | Kazan  |
```

**В SQL:** `SELECT *`

---

## 🎯 Полная картина

```sql
SELECT *              ← π* (все колонки)
FROM R CROSS JOIN S   ← R × S (все комбинации)
WHERE clause          ← σ (отфильтровать)
```

### **Дерево читается как рецепт:**

1. **Сначала (внизу):** Возьми таблицы R и S
2. **Потом (середина):** Сделай все комбинации (×), затем отфильтруй (σ)
3. **В конце (верх):** Покажи результат (π*)

---

## 🔥 Реальный пример из жизни

### SQL запрос:
```sql
SELECT *
FROM person CROSS JOIN pizzeria
WHERE person.age > 25
```

### Дерево:

```
         π*                     ← SELECT *
         ↑
         σ(age > 25)            ← WHERE age > 25
         ↑
         ×                      ← CROSS JOIN
        ↗ ↖
   person   pizzeria           ← таблицы
```

### Что происходит:

**1. CROSS JOIN (×):**
```
| name  | age | pizzeria_name |
|-------|-----|---------------|
| Anna  | 30  | Dominos       |
| Anna  | 30  | Pizza Hut     |
| Peter | 20  | Dominos       |
| Peter | 20  | Pizza Hut     |
```

**2. WHERE (σ):**
```
Фильтр: age > 25

| name  | age | pizzeria_name |
|-------|-----|---------------|
| Anna  | 30  | Dominos       |  ← только Anna (30 > 25)
| Anna  | 30  | Pizza Hut     |
```

**3. SELECT * (π*):**
```
Показываем все колонки → тот же результат
```

---

## 💡 Зачем это нужно?

### **База данных переводит твой SQL в дерево!**

```
Твой SQL → Дерево алгебры → Оптимизация → Выполнение
```

**Почему это важно:**
- База данных может **переставить операции** для скорости
- Например: сначала отфильтровать (σ), **потом** соединить (×) — быстрее!

```
Медленно:                      Быстро:
    π*                            π*
    ↑                             ↑
    σ                             ×
    ↑                            ↗ ↖
    × (1000 строк!)            σ(R)  S
   ↗ ↖                         (10 строк)
  R   S
```

---

## 📝 Шпаргалка по символам

| Символ | Название | SQL | Что делает |
|--------|----------|-----|------------|
| **×** | Декартово произведение | CROSS JOIN | Все комбинации строк |
| **σ** | Селекция | WHERE | Фильтрует строки |
| **π** | Проекция | SELECT | Выбирает колонки |
| **⋈** | Соединение | JOIN | Соединяет по условию |

---

