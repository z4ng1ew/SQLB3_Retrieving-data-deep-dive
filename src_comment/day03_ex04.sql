В SQL **INNER JOIN** и просто **JOIN** — это **одно и то же**. Нет никакой разницы.

По стандарту SQL, когда вы пишете `JOIN` без указания типа, это автоматически означает `INNER JOIN`.

**Примеры (эквивалентны):**

```sql
-- Вариант 1
SELECT * FROM users
JOIN orders ON users.id = orders.user_id;

-- Вариант 2 (то же самое)
SELECT * FROM users
INNER JOIN orders ON users.id = orders.user_id;
```

Оба запроса вернут **только те строки, где есть совпадения в обеих таблицах**.

**Когда имеет значение указание типа:**
- `LEFT JOIN` (LEFT OUTER JOIN) — вернёт все строки из левой таблицы
- `RIGHT JOIN` (RIGHT OUTER JOIN) — вернёт все строки из правой таблицы
- `FULL JOIN` (FULL OUTER JOIN) — вернёт все строки из обеих таблиц
- `CROSS JOIN` — декартово произведение

Большинство разработчиков пишут просто `JOIN`, потому что это короче и INNER JOIN используется чаще всего.



























