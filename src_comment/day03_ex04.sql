## ❓ Частые вопросы

### **Q1: Почему не сравниваем по позициям?**

**A:** "Потому что позиции строк в базе данных **НЕ гарантированы**! Строки могут быть в любом порядке. Сегодня Pizza Hut первая строка, завтра — третья. Но `id = 1` всегда будет `1`."

---

### **Q2: Зачем нужны эти ключи?**

**A:** 

**Первичный ключ:**
- Уникально идентифицирует каждую запись
- Как паспорт у человека

**Внешний ключ:**
- Связывает таблицы
- Гарантирует целостность данных
- Как адрес в записной книжке

---

### **Q3: Можно пример БЕЗ ключей?**

**A:**

**БЕЗ связи (плохо):**

```
menu:
┌────────────────┬─────────────┬───────┐
│ pizza_name     │ pizzeria    │ price │
├────────────────┼─────────────┼───────┤
│ cheese pizza   │ Pizza Hut   │ 900   │  ← дублирование!
│ pepperoni pizza│ Pizza Hut   │ 1200  │  ← дублирование!
│ mushroom pizza │ Pizza Hut   │ 1100  │  ← дублирование!
└────────────────┴─────────────┴───────┘

Проблемы:
❌ Дублирование данных
❌ Если изменить название "Pizza Hut" → надо обновить 100 строк
❌ Опечатки: "Pizza Hut" vs "Pizza hut" vs "PizzaHut"
```

**С внешним ключом (хорошо):**

```
menu:                       pizzeria:
┌────────────────┬────┐    ┌────┬──────────┐
│ pizza_name     │ 1  │────│ 1  │ Pizza Hut│
