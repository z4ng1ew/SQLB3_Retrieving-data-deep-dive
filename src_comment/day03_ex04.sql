## 🔗 Что такое Внешний ключ (Foreign Key)?

### **Внешний ключ = ссылка на другую таблицу**

```sql
CREATE TABLE menu (
    id BIGINT PRIMARY KEY,
    pizzeria_id BIGINT,              ← Внешний ключ!
    pizza_name VARCHAR,
    price NUMERIC,
    
    FOREIGN KEY (pizzeria_id) 
        REFERENCES pizzeria(id)      ← Ссылается на pizzeria.id
);
```

**Что это значит:**
- `pizzeria_id` хранит **номер** (ID) пиццерии
- Этот номер **должен существовать** в таблице `pizzeria`

**Аналогия:** Как адрес в записной книжке — "Пицца продаётся у человека с паспортом №123456"

